//go:build tsgen

// Command schema-ts generates TypeScript interfaces (matching the shape of
// nodelibs/schema/src/interfaces/*.ts, historically produced by
// nodelibs/schema/joi-to-ts from the Joi schemas) directly from the tagged Go
// structs under go-libs/schema/<folder>/models.go (+ private.go).
//
// Usage:
//
//	go run -tags=tsgen ./schema-ts --out <DIR> [--public] [--schema-dir DIR] [--interfaces-dir DIR]
//
// Only folders under --schema-dir that have a same-named .ts file already in
// --interfaces-dir are processed (Go-only folders such as scheduler/,
// repositorySync/ and validate/ are skipped, since there is no existing
// interface file to reproduce).
//
// In --public mode, types declared in private.go are skipped entirely
// (mirroring the old Joi `.meta({private:true})` convention); non-public mode
// includes them.
//
// See go-libs/Makefile targets gen-ts / gen-ts-public / gen-ts-parity.
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"sort"
	"strings"
)

// ---------------------------------------------------------------------
// Model
// ---------------------------------------------------------------------

type typeKind int

const (
	kindStruct typeKind = iota
	kindEnum            // named string type with a const block of values
	kindMap
	kindSlice
	kindScalar // named type over a Go predeclared scalar (string/bool/number), no enum
	kindAlias  // `type X = Y` (Go type alias)
)

type fieldInfo struct {
	goName    string
	jsonName  string
	optional  bool
	forceDate bool
	typeExpr  ast.Expr
	tag       string

	// tsOverride, when non-empty, is a verbatim TS type expression from the
	// field's `ts:"..."` struct tag. Go's type system can't express certain
	// TS shapes (unions, tuples), so this lets the canonical Go struct carry
	// the intended TS type explicitly. It overrides the reflected Go type;
	// optionality (`?`) is still derived from omitempty/pointer as usual.
	tsOverride string
}

type typeInfo struct {
	pkg         string
	name        string
	kind        typeKind
	structFlds  []*fieldInfo
	aliasRHS    ast.Expr // kindAlias: the aliased expr
	underlying  ast.Expr // raw RHS type expr as declared (for map/slice/scalar)
	enumValues  []string
	fromPrivate bool

	crossPkgRef bool // referenced (via selector) from another package

	// tsOverride, when non-empty, is a verbatim TS type expression from a
	// `//ts:<expr>` trailing line-comment directive on the type declaration.
	// A Go type alias/definition can't carry a struct tag, so this is the
	// type-level equivalent of fieldInfo.tsOverride: it lets a named
	// any-backed union type (e.g. `type Duration any //ts:string |
	// DurationObject`) emit `export type Duration = string | DurationObject;`
	// instead of reflecting the inexpressible Go underlying (`any`).
	tsOverride string

	// forceExport is set by a bare `//ts:export` trailing line-comment
	// directive. It forces the type to (a) be emitted as a named export with
	// its normal reflected shape and (b) be referenced by name at every use
	// site - the inverse of the `Parent+Field == TypeName` claiming
	// heuristic, which would otherwise inline it and drop the named export.
	// Used for types that OLD (the committed reference TS) exports by name
	// and downstream consumers import by name. Unlike tsOverride there is no
	// expression: only the naming/emit behaviour is forced, not the body.
	forceExport bool
}

type pkgInfo struct {
	name    string // folder / go package name
	tsFile  string // target ts filename (without dir), e.g. "gvc.ts"
	types   map[string]*typeInfo
	order   []string          // declaration order (models.go then private.go)
	imports map[string]string // local import alias -> resolved package folder name (from Go import path)

	// autoGenerated is true when models.go's leading comment is exactly
	// "/* auto-generated */" (as opposed to a "/* hand-maintained ..."
	// header). These packages were mechanically ported straight from the
	// old Joi schemas with a stable Go name for every object schema,
	// including ones the original Joi source always referenced by name at
	// every use site (never duplicated it inline). Hand-maintained packages
	// (gvc, workload, ...) instead follow the ParentField naming
	// convention only for genuinely-inlined-only shapes, and otherwise
	// duplicate a same-package struct inline at its direct (non-array,
	// non-map-value) use even when unclaimed (e.g. GvcSpec.staticPlacement)
	// - see fieldClaimsType / the kindStruct case in renderIdent.
	autoGenerated bool
}

type generator struct {
	pkgs       map[string]*pkgInfo
	publicMode bool
	// per-package: name -> field(s) that "claim" that name via Parent+Field concatenation
	claims map[string]map[string]bool // pkg -> typeName -> claimed (matched, excluding Spec/Status)
}

var identRe = regexp.MustCompile(`^[a-zA-Z_][0-9a-zA-Z_]+$`)

// alwaysReferenceLeaf is a small, evidence-based whitelist of cross-package
// SCALAR/SLICE-kind types that the original hand-written Joi source
// genuinely referenced by name everywhere (the "resource envelope" leaf
// types), as opposed to the much more common pattern in this codebase where
// a named scalar/slice alias (Cpu, Memory, ScheduleType, EnvCollection,
// Port, ImageLink, LocationOptions, ...) is exported once for documentation
// purposes but every actual usage site is a fresh inlined primitive/array
// literal. There is no general syntactic signal in the Go source to tell
// these apart; this whitelist was derived by diffing generator output
// against the committed interfaces for base/gvc/workload/query.
var alwaysReferenceLeaf = map[string]bool{
	"base.Name":  true,
	"base.Links": true,
	"base.Regex": true,
}

var dateJSONNames = map[string]bool{
	"created": true, "lastModified": true, "since": true, "expires": true,
	"validated": true, "statusUpdated": true, "lastChecked": true,
	"snapshotExpirationDate": true,
}

// ---------------------------------------------------------------------
// main
// ---------------------------------------------------------------------

func main() {
	out := flag.String("out", "", "output directory for generated .ts files (default: a fresh temp dir, printed to stderr)")
	public := flag.Bool("public", false, "public mode: skip types declared in private.go")
	schemaDir := flag.String("schema-dir", "go-libs/schema", "path to go-libs/schema")
	ifaceDir := flag.String("interfaces-dir", "nodelibs/schema/src/interfaces", "path to the existing target .ts interfaces dir (defines the file set to emit)")
	repoRoot := flag.String("repo-root", "", "repo root to resolve schema-dir/interfaces-dir against (default: cwd)")
	flag.Parse()

	root := *repoRoot
	if root == "" {
		wd, err := os.Getwd()
		if err != nil {
			fatal("getwd: %v", err)
		}
		root = wd
	}

	schemaDirAbs := abs(root, *schemaDir)
	ifaceDirAbs := abs(root, *ifaceDir)

	outDir := *out
	if outDir == "" {
		d, err := os.MkdirTemp("", "schema-ts-")
		if err != nil {
			fatal("mkdtemp: %v", err)
		}
		outDir = d
		fmt.Fprintf(os.Stderr, "no --out given, writing to temp dir: %s\n", outDir)
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		fatal("mkdir out: %v", err)
	}

	folders, err := matchedFolders(schemaDirAbs, ifaceDirAbs)
	if err != nil {
		fatal("%v", err)
	}

	g := &generator{pkgs: map[string]*pkgInfo{}, publicMode: *public, claims: map[string]map[string]bool{}}

	for _, folder := range folders {
		pi, err := g.parsePackage(schemaDirAbs, folder)
		if err != nil {
			fatal("parsing %s: %v", folder, err)
		}
		g.pkgs[folder] = pi
	}

	g.computeCrossPackageRefs()
	for pkgName := range g.pkgs {
		g.computeClaims(pkgName)
	}

	sortedFolders := make([]string, 0, len(folders))
	sortedFolders = append(sortedFolders, folders...)
	sort.Strings(sortedFolders)

	for _, folder := range sortedFolders {
		pi := g.pkgs[folder]
		content := g.renderFile(pi)
		outPath := filepath.Join(outDir, pi.tsFile)
		if err := os.WriteFile(outPath, []byte(content), 0o644); err != nil {
			fatal("write %s: %v", outPath, err)
		}
	}

	fmt.Fprintf(os.Stderr, "generated %d interface files into %s\n", len(sortedFolders), outDir)
	fmt.Println(outDir)
}

func abs(root, p string) string {
	if filepath.IsAbs(p) {
		return p
	}
	return filepath.Join(root, p)
}

func fatal(format string, args ...interface{}) {
	fmt.Fprintf(os.Stderr, "schema-ts: "+format+"\n", args...)
	os.Exit(1)
}

// matchedFolders returns the go-libs/schema subfolders that have a same-named
// <folder>.ts file already present in the interfaces dir.
func matchedFolders(schemaDir, ifaceDir string) ([]string, error) {
	entries, err := os.ReadDir(schemaDir)
	if err != nil {
		return nil, fmt.Errorf("reading schema dir: %w", err)
	}
	var out []string
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		tsPath := filepath.Join(ifaceDir, e.Name()+".ts")
		if _, err := os.Stat(tsPath); err == nil {
			// require a models.go to actually exist
			if _, err := os.Stat(filepath.Join(schemaDir, e.Name(), "models.go")); err == nil {
				out = append(out, e.Name())
			}
		}
	}
	sort.Strings(out)
	return out, nil
}

// ---------------------------------------------------------------------
// Parsing
// ---------------------------------------------------------------------

func (g *generator) parsePackage(schemaDir, folder string) (*pkgInfo, error) {
	pi := &pkgInfo{
		name:    folder,
		tsFile:  folder + ".ts",
		types:   map[string]*typeInfo{},
		imports: map[string]string{},
	}

	files := []string{filepath.Join(schemaDir, folder, "models.go")}
	if !g.publicMode {
		priv := filepath.Join(schemaDir, folder, "private.go")
		if _, err := os.Stat(priv); err == nil {
			files = append(files, priv)
		}
	}

	fset := token.NewFileSet()
	for _, f := range files {
		fromPrivate := strings.HasSuffix(f, "private.go")
		src, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		if !fromPrivate && strings.HasPrefix(string(src), "/* auto-generated */") {
			pi.autoGenerated = true
		}
		// ParseComments so the type-level `//ts:<expr>` trailing line-comment
		// directive (ast.TypeSpec.Comment / the GenDecl's trailing comment)
		// is attached and readable below.
		file, err := parser.ParseFile(fset, f, src, parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("parse %s: %w", f, err)
		}

		// collect import aliases -> package folder name (last path element)
		for _, imp := range file.Imports {
			p := strings.Trim(imp.Path.Value, `"`)
			pkgFolder := p[strings.LastIndex(p, "/")+1:]
			alias := pkgFolder
			if imp.Name != nil {
				alias = imp.Name.Name
			}
			pi.imports[alias] = pkgFolder
		}

		// pass 1: type decls
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				ti := &typeInfo{pkg: folder, name: ts.Name.Name, fromPrivate: fromPrivate}
				// Type-level `//ts:` directive: the trailing line comment on a
				// `type X <underlying> //ts:...` declaration attaches to the
				// TypeSpec's Comment group (with parser.ParseComments). The
				// bare `//ts:export` form is a flag (force named export +
				// always reference by name); any other `//ts:<expr>` is a
				// verbatim TS-type override.
				if d := tsDirective(ts.Comment); d != "" {
					if d == "export" {
						ti.forceExport = true
					} else {
						ti.tsOverride = d
					}
				}
				if ts.Assign != 0 {
					ti.kind = kindAlias
					ti.aliasRHS = ts.Type
				} else {
					switch t := ts.Type.(type) {
					case *ast.StructType:
						ti.kind = kindStruct
						ti.structFlds = parseFields(t)
					case *ast.MapType:
						ti.kind = kindMap
						ti.underlying = t
					case *ast.ArrayType:
						ti.kind = kindSlice
						ti.underlying = t
					default:
						ti.kind = kindScalar
						ti.underlying = t
					}
				}
				pi.types[ts.Name.Name] = ti
				pi.order = append(pi.order, ts.Name.Name)
			}
		}

		// pass 2: const blocks -> enum values
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.CONST {
				continue
			}
			var lastType string
			for _, spec := range gd.Specs {
				vs, ok := spec.(*ast.ValueSpec)
				if !ok {
					continue
				}
				typeName := lastType
				if id, ok := vs.Type.(*ast.Ident); ok {
					typeName = id.Name
					lastType = typeName
				}
				if typeName == "" || len(vs.Values) == 0 {
					continue
				}
				ti, ok := pi.types[typeName]
				if !ok {
					continue
				}
				for _, v := range vs.Values {
					if lit, ok := v.(*ast.BasicLit); ok && lit.Kind == token.STRING {
						val := strings.Trim(lit.Value, `"`+"`")
						ti.enumValues = append(ti.enumValues, val)
					}
				}
				if ti.kind == kindScalar && len(ti.enumValues) > 0 {
					ti.kind = kindEnum
				}
			}
		}
	}

	return pi, nil
}

func parseFields(t *ast.StructType) []*fieldInfo {
	var out []*fieldInfo
	if t.Fields == nil {
		return out
	}
	for _, f := range t.Fields.List {
		if len(f.Names) == 0 {
			continue // embedded field, not used in this schema convention
		}
		tag := ""
		if f.Tag != nil {
			tag = strings.Trim(f.Tag.Value, "`")
		}
		jsonName, skip := jsonNameFromTag(tag, f.Names[0].Name)
		if skip {
			continue
		}
		_, isPtr := f.Type.(*ast.StarExpr)
		hasOmitempty := strings.Contains(tag, ",omitempty") || strings.Contains(tag, ",omitzero")
		hasRequired := hasValidateToken(tag, "required")
		// validate:"required" always wins (some fields carry both the omit
		// tag - so zero values round-trip cleanly through Go JSON - and
		// validate:"required", e.g. enum fields with a default); absent that,
		// a bare (non-omit, non-pointer) field is required, and everything
		// else is optional. The port tags optionals ,omitzero (Go 1.24); the
		// legacy ,omitempty is kept for anything still using it.
		optional := !hasRequired && (isPtr || hasOmitempty)
		fd := forceDateFor(jsonName, tag)
		// Field-level `ts:"<expr>"` override: a verbatim TS type that
		// supersedes the reflected Go field type (optionality unaffected).
		tsOverride := reflect.StructTag(tag).Get("ts")
		for _, n := range f.Names {
			out = append(out, &fieldInfo{
				goName:     n.Name,
				jsonName:   jsonName,
				optional:   optional,
				forceDate:  fd,
				typeExpr:   f.Type,
				tag:        tag,
				tsOverride: tsOverride,
			})
		}
	}
	return out
}

// tsDirective extracts a `//ts:<expr>` type-level directive from a trailing
// line comment group, returning the trimmed verbatim TS expression (or ""
// when absent). Only an exact `//ts:` prefix (no space between `//` and
// `ts:`) is recognised, so ordinary comments never trigger it.
func tsDirective(cg *ast.CommentGroup) string {
	if cg == nil {
		return ""
	}
	for _, c := range cg.List {
		text := c.Text // includes the leading "//" or "/*"
		if strings.HasPrefix(text, "//ts:") {
			return strings.TrimSpace(strings.TrimPrefix(text, "//ts:"))
		}
	}
	return ""
}

func jsonNameFromTag(tag, goName string) (name string, skip bool) {
	// tag is the raw (unquoted-backtick) struct tag, e.g. json:"foo,omitempty" validate:"..."
	const key = `json:"`
	i := strings.Index(tag, key)
	if i < 0 {
		return goName, false
	}
	rest := tag[i+len(key):]
	j := strings.Index(rest, `"`)
	if j < 0 {
		return goName, false
	}
	parts := strings.Split(rest[:j], ",")
	if parts[0] == "-" {
		return "", true
	}
	if parts[0] == "" {
		return goName, false
	}
	return parts[0], false
}

func hasValidateToken(tag, token string) bool {
	for _, t := range validateTagTokens(tag) {
		if t == token {
			return true
		}
	}
	return false
}

// parseValidValues extracts an ad hoc `valid=a|b|c` enum from a field's
// validate tag. Some leaf scalar types (e.g. TaskStatus) carry their allowed
// values only on the field's validate tag rather than via a Go const block
// (which is how kindEnum is normally detected); this is the fallback that
// still lets those fields render as a TS string-literal union.
func parseValidValues(tag string) []string {
	for _, t := range validateTagTokens(tag) {
		if strings.HasPrefix(t, "valid=") {
			return strings.Split(strings.TrimPrefix(t, "valid="), "|")
		}
	}
	return nil
}

func validateTagTokens(tag string) []string {
	const key = `validate:"`
	i := strings.Index(tag, key)
	if i < 0 {
		return nil
	}
	rest := tag[i+len(key):]
	j := strings.Index(rest, `"`)
	if j < 0 {
		return nil
	}
	return strings.Split(rest[:j], ",")
}

func forceDateFor(jsonName, tag string) bool {
	for _, t := range validateTagTokens(tag) {
		if t == "date" {
			return true
		}
	}
	if dateJSONNames[jsonName] {
		return true
	}
	if strings.HasSuffix(jsonName, "At") || strings.HasSuffix(jsonName, "Date") {
		return true
	}
	return false
}

// ---------------------------------------------------------------------
// Cross-package reference pass
// ---------------------------------------------------------------------

// computeCrossPackageRefs walks every struct field's type expression across
// every package; any *ast.SelectorExpr (pkg.Type) found marks the referenced
// type (resolved via that package's imports) as cross-package referenced. It
// also handles type aliases (`type X = pkg.Y` or `type X = OtherLocalType`)
// by walking through the alias RHS.
func (g *generator) computeCrossPackageRefs() {
	for _, pi := range g.pkgs {
		for _, name := range pi.order {
			ti := pi.types[name]
			switch ti.kind {
			case kindStruct:
				for _, f := range ti.structFlds {
					g.markCrossPkg(pi, f.typeExpr)
				}
			case kindAlias:
				g.markCrossPkg(pi, ti.aliasRHS)
			case kindMap, kindSlice, kindScalar:
				if ti.underlying != nil {
					g.markCrossPkg(pi, ti.underlying)
				}
			}
		}
	}
}

func (g *generator) markCrossPkg(pi *pkgInfo, expr ast.Expr) {
	expr = unwrapPointer(expr)
	switch t := expr.(type) {
	case *ast.SelectorExpr:
		pkgAlias, ok := t.X.(*ast.Ident)
		if !ok {
			return
		}
		folder, ok := pi.imports[pkgAlias.Name]
		if !ok {
			return
		}
		target, ok := g.pkgs[folder]
		if !ok {
			return // referenced package isn't part of our matched set (e.g. k8s types) - ignore
		}
		if ti, ok := target.types[t.Sel.Name]; ok {
			ti.crossPkgRef = true
		}
	case *ast.ArrayType:
		g.markCrossPkg(pi, t.Elt)
	case *ast.MapType:
		g.markCrossPkg(pi, t.Value)
	case *ast.Ident:
		// local named type: if it's an alias, its RHS was/will be walked when
		// we process that type's own declaration; nothing to do here.
	}
}

func unwrapPointer(e ast.Expr) ast.Expr {
	if s, ok := e.(*ast.StarExpr); ok {
		return s.X
	}
	return e
}

// ---------------------------------------------------------------------
// Claims (name-derived inline detection)
// ---------------------------------------------------------------------

// computeClaims finds, for the given package, every type name that is
// "claimed" by some struct field elsewhere in the same package under the
// ParentTypeName+FieldName naming convention used throughout go-libs/schema
// to give explicit Go names to what are, in the TS output, anonymous nested
// object/enum/map shapes. A claimed type (other than via a field literally
// named Spec/Status, which are dual-emitted) does not get its own top-level
// TS declaration - it is inlined wherever it's used.
func (g *generator) computeClaims(pkgName string) {
	pi := g.pkgs[pkgName]
	claims := map[string]bool{}
	for _, name := range pi.order {
		ti := pi.types[name]
		if ti.kind != kindStruct {
			continue
		}
		for _, f := range ti.structFlds {
			expected := ti.name + pascalize(f.goName)
			target, ok := pi.types[expected]
			if !ok {
				continue
			}
			if (f.goName == "Spec" || f.goName == "Status") &&
				(target.kind == kindStruct || target.kind == kindMap) {
				// dual-emit exception: a resource root's Spec/Status
				// field (struct or bare map[string]any status) is always
				// inlined at that field AND kept standalone, mirroring
				// GvcSpec/WorkloadSpec/WorkloadStatus/GvcStatus. Plain
				// enum fields incidentally named "status" (e.g.
				// JobExecutionStatus.Status) are not part of this pattern
				// and fall through to normal name-derived claiming.
				continue
			}
			claims[expected] = true
		}
	}
	g.claims[pkgName] = claims
}

func fieldClaimsType(parent *typeInfo, f *fieldInfo, target *typeInfo) bool {
	if (f.goName == "Spec" || f.goName == "Status") &&
		(target.kind == kindStruct || target.kind == kindMap) {
		return true
	}
	return parent.name+pascalize(f.goName) == target.name
}

// pascalize normalizes a Go field name into the PascalCase form used for
// name-derivation matching. Hand-maintained packages already use plain
// PascalCase Go field names (e.g. "StaticPlacement"); some auto-generated
// packages (e.g. envoyCommon) instead keep the original snake_case JSON key
// capitalized only on the leading letter (e.g. "Service_account_jwt_access"),
// which needs normalizing to "ServiceAccountJwtAccess" before it can be
// compared against a same-package derived-shape type name.
func pascalize(name string) string {
	if !strings.Contains(name, "_") {
		return name
	}
	parts := strings.Split(name, "_")
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(p[1:])
	}
	return b.String()
}

// ---------------------------------------------------------------------
// Standalone-set computation
// ---------------------------------------------------------------------

func (g *generator) isStandalone(pi *pkgInfo, ti *typeInfo) bool {
	// A `//ts:` type-level override always emits its own `export type` (the
	// whole point is to give the named union a standalone TS declaration);
	// a `//ts:export` type is likewise always emitted (named export forced).
	if ti.tsOverride != "" || ti.forceExport {
		return true
	}
	if ti.kind == kindAlias {
		return false
	}
	if ti.crossPkgRef {
		return true
	}
	switch ti.kind {
	case kindStruct, kindEnum, kindMap:
		return !g.claims[pi.name][ti.name]
	default: // slice, scalar
		// Auto-generated packages were mechanically ported with a stable Go
		// name for every schema, including scalar/slice ones the Joi
		// source referenced by name at every use site (e.g. mk8sCommon's
		// Taints/PreInstallScript) or simply exported without ever using
		// (e.g. GoDuration/NodePoolName) - both still need a standalone
		// declaration. Hand-maintained packages follow the opposite
		// default (Cpu/Memory/ScheduleType/CIDRList/... collapse
		// everywhere and are never standalone) - see renderIdent's
		// kindSlice/kindScalar cases.
		if pi.autoGenerated {
			return !g.claims[pi.name][ti.name]
		}
		return false
	}
}

