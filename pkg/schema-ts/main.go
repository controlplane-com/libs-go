type importSet struct {
	order []string            // source ts file order of first use
	names map[string][]string // source ts file -> type names (first-use order)
	seen  map[string]bool

	// localRefs records same-file type names referenced BY NAME during
	// rendering (i.e. every registerImport call whose target lives in this
	// same .ts file). renderFile uses it to close the reference->emit loop:
	// a type can be reference-by-name at one use site while being "claimed"
	// (and thus pruned from the standalone set) by an unrelated field
	// elsewhere - e.g. ExternalPortTlsMinProtocolVersion is claimed by
	// ExternalPortTls.MinProtocolVersion yet referenced by name from the
	// case-variant ExternalPortTLS struct; OrgSpecLogging is claimed by
	// OrgSpec.Logging yet referenced by name via the OrgSpecExtraLogging
	// alias. Without this, such a type is referenced but never declared =
	// dangling reference / invalid TS.
	localRefs map[string]bool
}

func newImportSet() *importSet {
	return &importSet{names: map[string][]string{}, seen: map[string]bool{}, localRefs: map[string]bool{}}
}

func (s *importSet) add(fromTsFile, name string) {
	key := fromTsFile + "\x00" + name
	if s.seen[key] {
		return
	}
	s.seen[key] = true
	if _, ok := s.names[fromTsFile]; !ok {
		s.order = append(s.order, fromTsFile)
	}
	s.names[fromTsFile] = append(s.names[fromTsFile], name)
}

func (g *generator) renderFile(pi *pkgInfo) string {
	// Initial emit set: the types that are standalone by the normal rules.
	emit := map[string]bool{}
	for _, name := range pi.order {
		if g.isStandalone(pi, pi.types[name]) {
			emit[name] = true
		}
	}

	// Close the reference->emit loop: render the current emit set to a
	// throwaway buffer purely to discover which same-file types get
	// referenced by name (importSet.localRefs). Any such referenced type
	// that isn't yet emitted is a would-be dangling reference - add it and
	// repeat, since a newly-added type's own body may reference further
	// pruned types. Fixpoint terminates because pi.types is finite and emit
	// only grows.
	for {
		probe := newImportSet()
		for _, name := range pi.order {
			if emit[name] {
				g.renderStandalone(pi, pi.types[name], probe)
			}
		}
		added := false
		for ref := range probe.localRefs {
			if emit[ref] {
				continue
			}
			if _, ok := pi.types[ref]; ok {
				emit[ref] = true
				added = true
			}
		}
		if !added {
			break
		}
	}

	var standalone []string
	for name := range emit {
		standalone = append(standalone, name)
	}
	sort.Strings(standalone)

	imports := newImportSet()
	var body strings.Builder
	for _, name := range standalone {
		ti := pi.types[name]
		body.WriteString(g.renderStandalone(pi, ti, imports))
	}

	var importsBlock strings.Builder
	for _, tsFile := range imports.order {
		if tsFile == pi.tsFile {
			continue
		}
		names := dedupe(imports.names[tsFile])
		from := strings.TrimSuffix(tsFile, ".ts")
		importsBlock.WriteString(fmt.Sprintf("import { %s } from './%s.js';\n", strings.Join(names, ", "), from))
	}

	return "/* auto-generated */\n\n" + importsBlock.String() + "\n" + body.String()
}

func dedupe(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range in {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

func (g *generator) renderStandalone(pi *pkgInfo, ti *typeInfo, imports *importSet) string {
	// Type-level `//ts:<expr>` directive: emit the verbatim union/expr
	// instead of reflecting the (inexpressible) Go underlying type.
	if ti.tsOverride != "" {
		g.registerOverrideImports(pi, ti.tsOverride, imports)
		return fmt.Sprintf("export type %s = %s;\n\n", ti.name, ti.tsOverride)
	}
	switch ti.kind {
	case kindStruct:
		lit := g.renderStructLiteral(pi, ti, imports)
		return fmt.Sprintf("export interface %s %s\n\n", ti.name, lit)
	case kindEnum:
		return fmt.Sprintf("export type %s = %s;\n\n", ti.name, enumLiteral(ti.enumValues))
	case kindMap:
		valType := g.renderType(pi, ti.underlying.(*ast.MapType).Value, ti, &fieldInfo{}, imports, false)
		return fmt.Sprintf("export interface %s {\n  [x: string]: %s;\n\n}\n\n", ti.name, valType)
	case kindSlice:
		elemType := g.renderType(pi, ti.underlying.(*ast.ArrayType).Elt, ti, &fieldInfo{}, imports, true)
		return fmt.Sprintf("export type %s = %s[];\n\n", ti.name, elemType)
	case kindScalar:
		return fmt.Sprintf("export type %s = %s;\n\n", ti.name, scalarPrimitive(ti.underlying))
	}
	return ""
}

func enumLiteral(values []string) string {
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = "'" + v + "'"
	}
	return strings.Join(parts, " | ")
}

func (g *generator) renderStructLiteral(pi *pkgInfo, ti *typeInfo, imports *importSet) string {
	var b strings.Builder
	b.WriteString("{\n")
	for _, f := range ti.structFlds {
		var typ string
		if f.tsOverride != "" {
			// Field-level `ts:"<expr>"` override wins over the reflected type.
			typ = f.tsOverride
			g.registerOverrideImports(pi, typ, imports)
		} else {
			typ = g.renderType(pi, f.typeExpr, ti, f, imports, false)
		}
		opt := "?"
		if !f.optional {
			opt = ""
		}
		key := f.jsonName
		if !identRe.MatchString(key) {
			key = `"` + key + `"`
		}
		b.WriteString(fmt.Sprintf("  %s%s: %s;\n\n", key, opt, typ))
	}
	b.WriteString("}")
	return b.String()
}

// renderType renders the TS type for a field's Go type expression, given the
// struct (parent) it's declared on (for name-derived inline matching), the
// field itself (for optionality/date context - not used for the recursive
// element calls, which pass a zero-value fieldInfo), and whether we're
// currently rendering a "collection position" (an array element or map
// value) as opposed to a direct struct field. Collection position matters
// for unclaimed (non name-matched) same-package structs: those inline only
// in direct field position, and are referenced by name (forcing themselves
// standalone) in collection position - see computeClaims doc comment for the
// claimed/unclaimed split.
func (g *generator) renderType(pi *pkgInfo, expr ast.Expr, parent *typeInfo, f *fieldInfo, imports *importSet, inCollection bool) string {
	expr = unwrapPointer(expr)

	switch t := expr.(type) {
	case *ast.Ident:
		return g.renderIdent(pi, t.Name, parent, f, imports, inCollection)
	case *ast.SelectorExpr:
		return g.renderSelector(pi, t, f, imports)
	case *ast.ArrayType:
		// Preserve the originating field (parent, f) rather than resetting
		// it: a claimed element type is name-derived from the FIELD that
		// reaches it (e.g. ContainerSpecReadinessProbeHttpGet.HttpHeaders
		// claims ContainerSpecReadinessProbeHttpGetHttpHeaders as its
		// element type), even though the element sits behind an array.
		elem := g.renderType(pi, t.Elt, parent, f, imports, true)
		if strings.Contains(elem, "|") {
			elem = "(" + elem + ")"
		}
		return elem + "[]"
	case *ast.MapType:
		val := g.renderType(pi, t.Value, parent, f, imports, true)
		return fmt.Sprintf("{\n  [x: string]: %s;\n\n}", val)
	case *ast.InterfaceType:
		return "any"
	case *ast.StarExpr:
		return g.renderType(pi, t.X, parent, f, imports, inCollection)
	}
	return "any"
}

func (g *generator) renderIdent(pi *pkgInfo, name string, parent *typeInfo, f *fieldInfo, imports *importSet, inCollection bool) string {
	switch name {
	case "string":
		if vals := parseValidValues(f.tag); len(vals) > 0 {
			return enumLiteral(vals)
		}
		if f.forceDate {
			return "Date"
		}
		return "string"
	case "bool":
		return "boolean"
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64",
		"float32", "float64", "byte", "rune":
		return "number"
	case "any":
		return "any"
	}

	ti, ok := pi.types[name]
	if !ok {
		// unknown local identifier (shouldn't normally happen); fall back
		return "any"
	}

	// A `//ts:` directive type is ALWAYS referenced by name at use sites:
	// for a tsOverride union its real TS shape lives only in its standalone
	// `export type` declaration (its Go underlying is an inexpressible
	// `any`), and a `//ts:export` type is deliberately forced to a named
	// reference (inverse of the claiming heuristic). Either way it must
	// never be inlined even when name-derivation would otherwise "claim" it
	// (e.g. TermValue is claimed by Term.Value; WorkloadHealth by
	// Workload.Health). Scoped strictly to `//ts:`-directive types.
	if ti.tsOverride != "" || ti.forceExport {
		g.registerImport(pi, ti, imports)
		return ti.name
	}

	switch ti.kind {
	case kindAlias:
		return g.renderType(pi, ti.aliasRHS, parent, f, imports, inCollection)
	case kindStruct:
		if ti.crossPkgRef {
			g.registerImport(pi, ti, imports)
			return ti.name
		}
		claimed := fieldClaimsType(parent, f, ti)
		if claimed || (!inCollection && !pi.autoGenerated) {
			// claimed (name-derived-nested-shape, or the Spec/Status dual
			// pattern) always inlines; in hand-maintained packages,
			// unclaimed structs additionally inline in direct
			// (non-collection) field position (pi.autoGenerated is false
			// there) - see pkgInfo.autoGenerated doc comment.
			return g.renderStructLiteral(pi, ti, imports)
		}
		g.registerImport(pi, ti, imports)
		return ti.name
	case kindEnum, kindMap:
		if ti.crossPkgRef {
			g.registerImport(pi, ti, imports)
			return ti.name
		}
		if fieldClaimsType(parent, f, ti) {
			switch ti.kind {
			case kindEnum:
				return enumLiteral(ti.enumValues)
			case kindMap:
				val := g.renderType(pi, ti.underlying.(*ast.MapType).Value, ti, &fieldInfo{}, imports, true)
				return fmt.Sprintf("{\n  [x: string]: %s;\n\n}", val)
			}
		}
		g.registerImport(pi, ti, imports)
		return ti.name
	case kindSlice:
		if ti.crossPkgRef && alwaysReferenceLeaf[ti.pkg+"."+ti.name] {
			g.registerImport(pi, ti, imports)
			return ti.name
		}
		// In auto-generated packages, an unclaimed slice alias (e.g.
		// mk8sCommon.Taints) is referenced by name like a struct/enum/map
		// would be; in hand-maintained ones it always collapses to
		// elem[] - see pkgInfo.autoGenerated doc comment.
		if pi.autoGenerated && !fieldClaimsType(parent, f, ti) {
			g.registerImport(pi, ti, imports)
			return ti.name
		}
		// Preserve the originating (parent, f) through the collapse so a
		// claimed element type (e.g. ReadinessHttpHeaderList's element
		// ContainerSpecReadinessProbeHttpGetHttpHeaders, name-derived from
		// the *field* that reaches the list) still inlines correctly.
		elem := g.renderType(pi, ti.underlying.(*ast.ArrayType).Elt, parent, f, imports, true)
		if strings.Contains(elem, "|") {
			elem = "(" + elem + ")"
		}
		return elem + "[]"
	case kindScalar:
		if ti.crossPkgRef && alwaysReferenceLeaf[ti.pkg+"."+ti.name] {
			g.registerImport(pi, ti, imports)
			return ti.name
		}
		if pi.autoGenerated && !fieldClaimsType(parent, f, ti) {
			g.registerImport(pi, ti, imports)
			return ti.name
		}
		prim := scalarPrimitive(ti.underlying)
		if prim == "string" {
			if vals := parseValidValues(f.tag); len(vals) > 0 {
				return enumLiteral(vals)
			}
			if f.forceDate {
				return "Date"
			}
		}
		return prim
	}
	return "any"
}

// renderCrossPkgElem resolves the element type of a cross-package collection
// alias (e.g. env.EnvCollection = []EnvVar) - it registers any needed import
// against the ORIGINAL calling package pi (not the target package the
// element type is declared in), which is what distinguishes it from just
// calling renderType(target, ...): that would use target as "self" for
// import-skipping purposes and silently drop the (very much needed) import.
func (g *generator) renderCrossPkgElem(pi *pkgInfo, target *pkgInfo, expr ast.Expr, imports *importSet) string {
	expr = unwrapPointer(expr)
	id, ok := expr.(*ast.Ident)
	if !ok {
		return "any"
	}
	switch id.Name {
	case "string", "bool", "any", "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64", "float32", "float64", "byte", "rune":
		return scalarPrimitive(id)
	}
	ti, ok := target.types[id.Name]
	if !ok {
		return "any"
	}
	g.registerImport(pi, ti, imports)
	return ti.name
}

func (g *generator) renderSelector(pi *pkgInfo, sel *ast.SelectorExpr, f *fieldInfo, imports *importSet) string {
	pkgAlias, ok := sel.X.(*ast.Ident)
	if !ok {
		return "any"
	}
	folder, ok := pi.imports[pkgAlias.Name]
	if !ok {
		return "any"
	}
	target, ok := g.pkgs[folder]
	if !ok {
		return "any"
	}
	ti, ok := target.types[sel.Sel.Name]
	if !ok {
		return "any"
	}
	// A cross-package `//ts:` directive type (e.g. envoyHttp.HttpFilter or a
	// `//ts:export` type like env.EnvName referenced from another package)
	// is always referenced by name - same rule as the local-Ident path in
	// renderIdent. Must precede the scalar-collapse below, which would
	// otherwise emit its primitive/`any` underlying.
	if ti.tsOverride != "" || ti.forceExport {
		g.registerImport(pi, ti, imports)
		return ti.name
	}
	// SCALAR/SLICE-kind cross-package types follow the same
	// collapse-unless-whitelisted rule as a local alias resolving to one
	// (see alwaysReferenceLeaf) - most of them (port.Port, env.EnvCollection,
	// ...) are validation-only Go leaf types with no real TS identity. This
	// only holds for hand-maintained *calling* packages though - an
	// auto-generated caller (e.g. envoyExcExtAuth referencing port.Port)
	// keeps the stable cross-package name, matching how it treats its own
	// unclaimed same-package scalar/slice types (see renderIdent).
	if !alwaysReferenceLeaf[ti.pkg+"."+ti.name] && !pi.autoGenerated {
		switch ti.kind {
		case kindScalar:
			prim := scalarPrimitive(ti.underlying)
			if prim == "string" {
				if vals := parseValidValues(f.tag); len(vals) > 0 {
					return enumLiteral(vals)
				}
				if f.forceDate {
					return "Date"
				}
			}
			return prim
		case kindSlice:
			elem := g.renderCrossPkgElem(pi, target, ti.underlying.(*ast.ArrayType).Elt, imports)
			if strings.Contains(elem, "|") {
				elem = "(" + elem + ")"
			}
			return elem + "[]"
		}
	}
	g.registerImport(pi, ti, imports)
	return ti.name
}

func (g *generator) registerImport(pi *pkgInfo, ti *typeInfo, imports *importSet) {
	targetPkg := g.pkgs[ti.pkg]
	if targetPkg == nil {
		return
	}
	if targetPkg.tsFile == pi.tsFile {
		// Same-file by-name reference: no import needed, but record it so
		// renderFile can guarantee the referenced type is actually declared
		// (see importSet.localRefs).
		imports.localRefs[ti.name] = true
		return
	}
	imports.add(targetPkg.tsFile, ti.name)
}

var overrideIdentRe = regexp.MustCompile(`[A-Za-z_][A-Za-z0-9_]*`)

// registerOverrideImports scans a verbatim `ts:`/`//ts:` override expression
// for referenced type names and registers the import for any that resolve to
// a type declared in a *different* matched package. Same-package references
// (e.g. envoyCommon's DurationObject, envoyHttp's ExtAuthz) need no import -
// they emit standalone in the same file - and TS primitives never match a
// type name, so they're ignored. When a bare identifier is ambiguous (a type
// of that name exists in more than one other package) it is left alone; the
// override author can qualify with the already-imported TS name instead.
func (g *generator) registerOverrideImports(pi *pkgInfo, expr string, imports *importSet) {
	for _, ident := range overrideIdentRe.FindAllString(expr, -1) {
		if _, ok := pi.types[ident]; ok {
			continue // same-package reference: no import needed
		}
		var matches []*typeInfo
		for _, other := range g.pkgs {
			if other.tsFile == pi.tsFile {
				continue
			}
			if ti, ok := other.types[ident]; ok {
				matches = append(matches, ti)
			}
		}
		if len(matches) == 1 {
			g.registerImport(pi, matches[0], imports)
		}
	}
}

func scalarPrimitive(expr ast.Expr) string {
	if id, ok := expr.(*ast.Ident); ok {
		switch id.Name {
		case "string":
			return "string"
		case "bool":
			return "boolean"
		case "int", "int8", "int16", "int32", "int64",
			"uint", "uint8", "uint16", "uint32", "uint64",
			"float32", "float64", "byte", "rune":
			return "number"
		case "any":
			return "any"
		}
	}
	return "any"
}
